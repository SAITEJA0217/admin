export interface PresignedUrlResponse {
  uploadUrl: string; // The single-use address generated by AWS
  key: string;       // The unique resource path tracking token for your database
}

/**
 * Handles the complete secure two-stage direct-to-S3 cloud streaming cycle.
 *
 * @param file - Raw File layout from local upload dropzone states
 * @param token - Authenticated Founder Authorization header bearer token string
 */
export async function uploadPitchDeckDirectToS3(file: File, token: string): Promise<string> {
  // --- Stage A: Request structural signatures tokens from your API Gateway ---
  const tokenResponse = await fetch("http://13.60.41.32:3000/api/v1/storage/presigned-url", {
    method: "POST",
    headers: {
      "Authorization": `Bearer ${token}`,
      "Content-Type": "application/json",
      "accept": "application/json"
    },
    body: JSON.stringify({
      fileName: file.name,
      fileType: file.type || "application/pdf" // defaults safely to standard document schemas
    })
  });

  if (!tokenResponse.ok) {
    const errBody = await tokenResponse.json().catch(() => ({}));
    throw new Error(errBody.message || `Presigned request rejected with status: ${tokenResponse.status}`);
  }

  const { uploadUrl, key }: PresignedUrlResponse = await tokenResponse.json();

  // --- Stage B: Put raw file binaries directly up inside S3 bucket storage ---
  const s3Response = await fetch(uploadUrl, {
    method: "PUT",
    headers: {
      "Content-Type": file.type || "application/pdf" // S3 explicitly requires matching Content-Types
    },
    body: file // Send the raw file binary buffer completely raw, NO FormData wrapping wrapper!
  });

  if (!s3Response.ok) {
    throw new Error(`Direct AWS cloud storage transmission pipeline aborted by target bucket: ${s3Response.statusText}`);
  }

  // Return the permanent key storage mapping token to save down inside profile tables later
  return key;
}
